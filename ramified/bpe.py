"""Ramified / hierarchical BPE.

A tokenizer is a finite presentation G = (A, R):
- A is the terminal alphabet (characters).
- R is a finite set of merge rules, organised in levels.
- S(G) is the set of finite symbols generated by R (the initial algebra).
- Encoding maps a string to a sequence of symbols; decoding expands them back.

The tree returned by encode_nodes() is the derivation forest. It is the
"ramified" object: the same flat token sequence, but with its internal
structure preserved.
"""

from __future__ import annotations

from dataclasses import dataclass
from collections import Counter, defaultdict
import heapq
import re

EOW = "\u0000</w>"  # sentinel; never appears in real text


@dataclass
class Node:
    symbol: int
    children: tuple["Node", ...] = ()


@dataclass
class MergeRule:
    left: int
    right: int
    new: int
    rank: int
    level: int
    count: int = 0


def _update_pair_counts(seq, delta, pair_counts, pair_words, wi):
    """Update pair counts and return every pair whose count changed.

    The caller must push the returned pairs onto the heap. In particular, a
    decrement that leaves a pair with a positive count elsewhere must be
    pushed: otherwise the heap keeps only the old, larger count, rejects it
    when popped, and the pair becomes invisible. That was the v0.1 bug
    (review F1).
    """
    touched = []
    for i in range(len(seq) - 1):
        p = (seq[i], seq[i + 1])
        new_count = pair_counts.get(p, 0) + delta
        if new_count <= 0:
            pair_counts.pop(p, None)
            pair_words.pop(p, None)
            continue
        pair_counts[p] = new_count
        if delta > 0:
            pair_words[p].add(wi)
        else:
            bucket = pair_words.get(p)
            if bucket is not None:
                bucket.discard(wi)
        touched.append((p, new_count))
    return touched


def train_bpe(sequences, freqs, n_merges, next_id, level, expansions):
    """Greedy BPE training on integer sequences.

    Returns (merges, updated_sequences). The updated sequences are the input
    for the next level of a hierarchical tokenizer.
    """
    words = [list(s) for s in sequences]
    pair_counts = Counter()
    pair_words = defaultdict(set)

    for wi, seq in enumerate(words):
        f = freqs[wi]
        for i in range(len(seq) - 1):
            p = (seq[i], seq[i + 1])
            pair_counts[p] += f
            pair_words[p].add(wi)

    heap = [(-c, p) for p, c in pair_counts.items() if c > 0]
    heapq.heapify(heap)

    merges = []
    for step in range(n_merges):
        pair = None
        while heap:
            negc, p = heapq.heappop(heap)
            if pair_counts.get(p, 0) == -negc and -negc > 0:
                pair = p
                break
        if pair is None:
            break

        a, b = pair
        new_id = next_id
        next_id += 1
        rule = MergeRule(a, b, new_id, step, level, -negc)
        merges.append(rule)
        expansions[new_id] = expansions[a] + expansions[b]

        for wi in list(pair_words.get(pair, ())):
            seq = words[wi]
            if not any(seq[i] == a and seq[i + 1] == b for i in range(len(seq) - 1)):
                pair_words[pair].discard(wi)
                continue

            f = freqs[wi]

            # Push every changed count, including decrements that leave the
            # pair positive in another word. Without the decrement pushes the
            # heap keeps a stale larger count, rejects it on pop, and the pair
            # becomes invisible (review F1).
            touched = _update_pair_counts(seq, -f, pair_counts, pair_words, wi)
            for p2, c2 in touched:
                heapq.heappush(heap, (-c2, p2))

            new_seq = []
            i = 0
            while i < len(seq):
                if i < len(seq) - 1 and seq[i] == a and seq[i + 1] == b:
                    new_seq.append(new_id)
                    i += 2
                else:
                    new_seq.append(seq[i])
                    i += 1

            words[wi] = new_seq
            touched = _update_pair_counts(new_seq, +f, pair_counts, pair_words, wi)
            for p2, c2 in touched:
                heapq.heappush(heap, (-c2, p2))

    return merges, words


class Tokenizer:
    def __init__(self, expansions, char_to_id, eow_id, levels, unk_id):
        self.expansions = expansions
        self.char_to_id = char_to_id
        self.eow_id = eow_id
        self.unk_id = unk_id
        self.levels = levels
        self.level_rank = [{(m.left, m.right): m.rank for m in rules} for rules in levels]
        self.level_map = [{(m.left, m.right): m.new for m in rules} for rules in levels]
        self.vocab_size = len(expansions)

    def encode_nodes(self, word: str, eow: bool = True) -> list[Node]:
        nodes = [Node(self.char_to_id.get(c, self.unk_id)) for c in word]
        if eow:
            nodes.append(Node(self.eow_id))
        for level in range(len(self.levels)):
            nodes = self._apply_level(nodes, level)
        return nodes

    def _apply_level(self, nodes: list[Node], level: int) -> list[Node]:
        ranks = self.level_rank[level]
        mapping = self.level_map[level]
        while True:
            best_rank = None
            best_idx = -1
            for i in range(len(nodes) - 1):
                pair = (nodes[i].symbol, nodes[i + 1].symbol)
                r = ranks.get(pair)
                if r is not None and (best_rank is None or r < best_rank):
                    best_rank = r
                    best_idx = i
            if best_idx < 0:
                break
            left = nodes[best_idx]
            right = nodes[best_idx + 1]
            new_id = mapping[(left.symbol, right.symbol)]
            nodes[best_idx:best_idx + 2] = [Node(new_id, (left, right))]
        return nodes

    def encode(self, word: str, eow: bool = True) -> list[int]:
        return [n.symbol for n in self.encode_nodes(word, eow)]

    def decode(self, ids) -> str:
        return "".join(self.expansions[i] for i in ids)

    def word_boundaries(self, word: str) -> list[int]:
        """Internal token boundaries of a word, excluding 0 and len(word)."""
        nodes = self.encode_nodes(word, eow=True)
        lengths = [len(self.expansions[n.symbol]) for n in nodes]
        word_len = len(word)
        out = []
        cum = 0
        for length in lengths[:-1]:
            cum += length
            if 0 < cum < word_len:
                out.append(cum)
        return out


def split_budget(total, weights):
    """Split an integer budget according to weights, summing exactly to total."""
    if total <= 0:
        return [0] * len(weights)
    raw = [total * w for w in weights]
    out = [int(x) for x in raw]
    remainder = total - sum(out)
    # distribute the remainder to the largest fractional parts
    order = sorted(range(len(raw)), key=lambda i: raw[i] - out[i], reverse=True)
    for i in range(remainder):
        out[order[i % len(order)]] += 1
    return out


def train_tokenizer(texts, vocab_size, n_levels=1, level_weights=None, min_freq=1, split="words"):
    """Train a flat (n_levels=1) or hierarchical BPE tokenizer.

    split="words"  -> regex tokens (word / punctuation separated), v0.1
    split="chunks" -> whitespace-separated chunks, matches tokenize_chunks
    """
    words = []
    for text in texts:
        if split == "chunks":
            words.extend(text.split())
        else:
            words.extend(re.findall(r"\w+|[^\w\s]", text))

    freq = Counter(words)
    if min_freq > 1:
        freq = Counter({w: c for w, c in freq.items() if c >= min_freq})
    if not freq:
        raise ValueError("empty corpus")

    chars = sorted(set("".join(freq.keys())))
    char_to_id = {c: i for i, c in enumerate(chars)}
    unk_id = len(chars)
    eow_id = unk_id + 1
    expansions = {i: c for c, i in char_to_id.items()}
    expansions[unk_id] = "<unk>"
    expansions[eow_id] = EOW

    next_id = eow_id + 1
    sequences = [[char_to_id[c] for c in w] + [eow_id] for w in freq]
    freqs = list(freq.values())

    total_merges = max(0, vocab_size - len(chars) - 2)
    if level_weights is None:
        level_weights = [1.0 / n_levels] * n_levels
    budgets = split_budget(total_merges, level_weights)

    levels = []
    for level in range(n_levels):
        merges, sequences = train_bpe(
            sequences, freqs, budgets[level], next_id, level, expansions
        )
        next_id += len(merges)
        levels.append(merges)
        if not merges:
            break

    return Tokenizer(expansions, char_to_id, eow_id, levels, unk_id)


def tokenize_normalized(text, tok):
    """Tokenize whitespace-normalised text; EOW marks word boundaries."""
    text = re.sub(r"\s+", " ", text).strip()
    ids = []
    for m in re.finditer(r"\w+|[^\w\s]", text):
        s = m.group()
        if re.fullmatch(r"\w+", s):
            ids.extend(tok.encode(s, eow=True))
        else:
            for c in s:
                ids.append(tok.char_to_id.get(c, tok.unk_id))
    return ids


def detokenize(ids, tok):
    raw = tok.decode(ids)
    return raw.replace(EOW, " ").strip()
